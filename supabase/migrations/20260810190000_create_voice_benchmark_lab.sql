create extension if not exists pgcrypto;

create table if not exists public.voice_benchmark_experiments (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.va_users(id) on delete cascade,
  name text not null,
  description text,
  status text not null default 'draft' check (status in ('draft', 'running', 'completed', 'archived')),
  repetition_count integer not null default 20 check (repetition_count between 1 and 100),
  randomized_order boolean not null default true,
  blind_comparison boolean not null default true,
  include_cold_runs boolean not null default true,
  environment_snapshot jsonb not null default '{}'::jsonb,
  methodology jsonb not null default '{}'::jsonb,
  share_slug text unique,
  is_public boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.voice_benchmark_variants (
  id uuid primary key default gen_random_uuid(),
  experiment_id uuid not null references public.voice_benchmark_experiments(id) on delete cascade,
  slot text not null check (slot in ('A', 'B', 'C')),
  name text not null,
  architecture text not null check (architecture in ('openai_native', 'openai_elevenlabs_flash', 'openai_elevenlabs_expressive', 'elevenlabs_agent', 'custom')),
  provider text not null,
  model text,
  voice text,
  agent_config_id uuid references public.va_agent_configs(id) on delete set null,
  config_snapshot jsonb not null,
  estimated_cost_per_minute numeric,
  created_at timestamptz not null default now(),
  unique (experiment_id, slot)
);

create table if not exists public.voice_benchmark_scenarios (
  id uuid primary key default gen_random_uuid(),
  experiment_id uuid not null references public.voice_benchmark_experiments(id) on delete cascade,
  scenario_key text not null,
  name text not null,
  category text not null,
  prompt text not null,
  input_transcript text,
  prerecorded_audio_url text,
  expected_behavior jsonb not null default '{}'::jsonb,
  settings jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (experiment_id, scenario_key)
);

create table if not exists public.voice_benchmark_runs (
  id uuid primary key default gen_random_uuid(),
  experiment_id uuid not null references public.voice_benchmark_experiments(id) on delete cascade,
  variant_id uuid not null references public.voice_benchmark_variants(id) on delete cascade,
  scenario_id uuid not null references public.voice_benchmark_scenarios(id) on delete cascade,
  run_number integer not null,
  run_order integer not null,
  trace_id uuid not null default gen_random_uuid(),
  session_id uuid references public.va_sessions(id) on delete set null,
  temperature text not null default 'warm' check (temperature in ('cold', 'warm')),
  status text not null default 'queued' check (status in ('queued', 'running', 'completed', 'failed', 'cancelled')),
  successful boolean,
  failure_reason text,
  user_transcript text,
  assistant_transcript text,
  input_audio_url text,
  output_audio_url text,
  config_snapshot jsonb not null,
  environment_snapshot jsonb not null default '{}'::jsonb,
  usage_snapshot jsonb not null default '{}'::jsonb,
  rating_snapshot jsonb,
  waveform_snapshot jsonb not null default '{}'::jsonb,
  estimated_cost numeric,
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (experiment_id, variant_id, scenario_id, run_number)
);

create table if not exists public.voice_benchmark_events (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.voice_benchmark_runs(id) on delete cascade,
  trace_id uuid not null,
  turn_id uuid,
  event_type text not null,
  clock_domain text not null default 'browser',
  monotonic_ms double precision not null,
  wall_time timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.voice_benchmark_metrics (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.voice_benchmark_runs(id) on delete cascade,
  metric_name text not null,
  metric_value double precision not null,
  unit text not null default 'ms',
  phase text,
  created_at timestamptz not null default now(),
  unique (run_id, metric_name)
);

create table if not exists public.voice_benchmark_ratings (
  id uuid primary key default gen_random_uuid(),
  run_id uuid not null references public.voice_benchmark_runs(id) on delete cascade,
  reviewer_id uuid references public.va_users(id) on delete set null,
  blind_label text,
  naturalness smallint check (naturalness between 1 and 5),
  expressiveness smallint check (expressiveness between 1 and 5),
  emotional_appropriateness smallint check (emotional_appropriateness between 1 and 5),
  pronunciation smallint check (pronunciation between 1 and 5),
  transcript_accuracy smallint check (transcript_accuracy between 1 and 5),
  semantic_correctness smallint check (semantic_correctness between 1 and 5),
  voice_consistency smallint check (voice_consistency between 1 and 5),
  turn_taking smallint check (turn_taking between 1 and 5),
  instruction_following smallint check (instruction_following between 1 and 5),
  quality_flags jsonb not null default '{}'::jsonb,
  notes text,
  created_at timestamptz not null default now()
);

create index if not exists idx_voice_benchmark_runs_experiment on public.voice_benchmark_runs(experiment_id, status);
create index if not exists idx_voice_benchmark_events_run on public.voice_benchmark_events(run_id, monotonic_ms);
create index if not exists idx_voice_benchmark_metrics_name on public.voice_benchmark_metrics(metric_name, metric_value);
create index if not exists idx_voice_benchmark_public_reports on public.voice_benchmark_experiments(share_slug) where is_public;

