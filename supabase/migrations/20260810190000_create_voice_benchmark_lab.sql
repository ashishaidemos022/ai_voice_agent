create or replace function public.owns_voice_benchmark_experiment(target_experiment_id uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.voice_benchmark_experiments e
    join public.va_users u on u.id = e.user_id
    where e.id = target_experiment_id and u.auth_user_id = auth.uid()
  );
$$;

create policy "benchmark experiments owner all" on public.voice_benchmark_experiments
  for all using (public.owns_voice_benchmark_experiment(id)) with check (
    exists (select 1 from public.va_users u where u.id = user_id and u.auth_user_id = auth.uid())
  );
create policy "benchmark variants owner all" on public.voice_benchmark_variants
  for all using (public.owns_voice_benchmark_experiment(experiment_id)) with check (public.owns_voice_benchmark_experiment(experiment_id));
create policy "benchmark scenarios owner all" on public.voice_benchmark_scenarios
  for all using (public.owns_voice_benchmark_experiment(experiment_id)) with check (public.owns_voice_benchmark_experiment(experiment_id));
create policy "benchmark runs owner all" on public.voice_benchmark_runs
  for all using (public.owns_voice_benchmark_experiment(experiment_id)) with check (public.owns_voice_benchmark_experiment(experiment_id));
create policy "benchmark events owner all" on public.voice_benchmark_events
  for all using (exists (select 1 from public.voice_benchmark_runs r where r.id = run_id and public.owns_voice_benchmark_experiment(r.experiment_id)))
  with check (exists (select 1 from public.voice_benchmark_runs r where r.id = run_id and public.owns_voice_benchmark_experiment(r.experiment_id)));
create policy "benchmark metrics owner all" on public.voice_benchmark_metrics
  for all using (exists (select 1 from public.voice_benchmark_runs r where r.id = run_id and public.owns_voice_benchmark_experiment(r.experiment_id)))
  with check (exists (select 1 from public.voice_benchmark_runs r where r.id = run_id and public.owns_voice_benchmark_experiment(r.experiment_id)));
create policy "benchmark ratings owner all" on public.voice_benchmark_ratings
  for all using (exists (select 1 from public.voice_benchmark_runs r where r.id = run_id and public.owns_voice_benchmark_experiment(r.experiment_id)))
  with check (exists (select 1 from public.voice_benchmark_runs r where r.id = run_id and public.owns_voice_benchmark_experiment(r.experiment_id)));

create or replace function public.get_public_voice_benchmark_report(target_slug text)
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'experiment', jsonb_build_object(
      'id', e.id, 'name', e.name, 'description', e.description, 'status', e.status,
      'repetition_count', e.repetition_count, 'randomized_order', e.randomized_order,
      'blind_comparison', e.blind_comparison, 'include_cold_runs', e.include_cold_runs,
      'methodology', e.methodology, 'share_slug', e.share_slug,
      'created_at', e.created_at, 'updated_at', e.updated_at
    ),
    'variants', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', v.id, 'slot', v.slot, 'name', v.name, 'architecture', v.architecture,
        'provider', v.provider, 'model', v.model,
        'estimated_cost_per_minute', v.estimated_cost_per_minute
      ) order by v.slot) from public.voice_benchmark_variants v where v.experiment_id = e.id
    ), '[]'::jsonb),
    'scenarios', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', s.id, 'scenario_key', s.scenario_key, 'name', s.name, 'category', s.category,
        'prompt', s.prompt, 'input_transcript', s.input_transcript,
        'expected_behavior', s.expected_behavior, 'settings', s.settings
      )) from public.voice_benchmark_scenarios s where s.experiment_id = e.id
    ), '[]'::jsonb),
    'runs', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', r.id, 'variant_id', r.variant_id, 'scenario_id', r.scenario_id,
        'run_number', r.run_number, 'run_order', r.run_order, 'trace_id', r.trace_id,
        'temperature', r.temperature, 'status', r.status, 'successful', r.successful,
        'failure_reason', r.failure_reason, 'user_transcript', r.user_transcript,
        'assistant_transcript', r.assistant_transcript, 'output_audio_url', r.output_audio_url,
        'rating_snapshot', r.rating_snapshot,
        'waveform_snapshot', r.waveform_snapshot,
        'estimated_cost', r.estimated_cost, 'started_at', r.started_at, 'completed_at', r.completed_at,
        'events', coalesce((select jsonb_agg(jsonb_build_object(
          'id', ev.id, 'trace_id', ev.trace_id, 'turn_id', ev.turn_id,
          'event_type', ev.event_type, 'clock_domain', ev.clock_domain,
          'monotonic_ms', ev.monotonic_ms, 'wall_time', ev.wall_time
        ) order by ev.monotonic_ms) from public.voice_benchmark_events ev where ev.run_id = r.id), '[]'::jsonb),
        'metrics', coalesce((select jsonb_agg(jsonb_build_object(
          'metric_name', m.metric_name, 'metric_value', m.metric_value, 'unit', m.unit, 'phase', m.phase
        )) from public.voice_benchmark_metrics m where m.run_id = r.id), '[]'::jsonb)
      ) order by r.run_order) from public.voice_benchmark_runs r where r.experiment_id = e.id
    ), '[]'::jsonb)
  )
  from public.voice_benchmark_experiments e
  where e.share_slug = target_slug and e.is_public = true;
$$;

revoke all on function public.get_public_voice_benchmark_report(text) from public;
grant execute on function public.get_public_voice_benchmark_report(text) to anon, authenticated;

